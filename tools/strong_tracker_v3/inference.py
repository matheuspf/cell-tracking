def prepare_export_attestation(ctx, variant):
    """Evaluation-only process: export only graph hashes, never scores or counts."""
    import csv
    from .common import sha, write_json
    if _ANNOTATION_GUARDS:
        raise RuntimeError('Build the score attestation in a separate evaluation-only process')
    source = ctx.out / 'score_rows.csv'
    source_hash = sha(source)
    score_variant = 'incumbent' if variant in {'incumbent', 'bypass_motion_bounds'} else variant
    with source.open(newline='') as handle:
        selected = [{key:row[key] for key in ['dataset', 'graph_file_sha256', 'scorer_hash']}
                    for row in csv.DictReader(handle) if row['variant'] == score_variant]
    assert sha(source) == source_hash, 'Official score rows changed while binding export hashes'
