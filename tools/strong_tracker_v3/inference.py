def stream_fresh_evidence(ctx, workers=2):
    """Consume newly completed fresh graphs while neural inference continues."""
    import multiprocessing as mp
    import time
    from concurrent.futures import ProcessPoolExecutor, wait, FIRST_COMPLETED
    from .common import read_json, write_json
    tasks = []
    for shard in sorted((ctx.out / 'fresh_full').glob('shard*')):
        tasks.extend((ctx, sample, shard) for sample in read_json(shard / 'inputs.json'))
    ordering = {sample['dataset']: i for i, sample in enumerate(ctx.samples())}
    tasks.sort(key=lambda task: ordering[task[1]['dataset']])
    assert len(tasks) == 199
    pending = list(tasks)
    done = []
    with ProcessPoolExecutor(max_workers=workers, mp_context=mp.get_context('spawn')) as pool:
        futures = {}
        while pending or futures:
            for task in list(pending):
                if len(futures) >= workers:
                    break
                _, sample, shard = task
                path = shard / 'fresh/incumbent' / f"{sample['dataset']}.json"
                if path.exists():
                    futures[pool.submit(fresh_evidence_one, task)] = task
                    pending.remove(task)
            if not futures:
                time.sleep(10)
                continue
            completed, _ = wait(futures, timeout=10, return_when=FIRST_COMPLETED)
            for future in completed:
                result = future.result()
                done.append(result)
                del futures[future]
                print('Fresh evidence', len(done), '/199', result, flush=True)
    write_json(ctx.out / 'fresh_evidence_receipt.json', dict(samples=len(done), records=done,
        annotation_reads=0, fresh_image_native_teacher_features=True))


