def teacher_native_parity_audit(ctx, *, require_complete=False):
    """Read-only reconciliation of original, canonical teacher and native evidence."""
    import numpy as np
    from .common import load_graph, read_json, sha, write_json
    rows = []
    bounds_nodes, tie_nodes, unexplained, shifted = 0, 0, 0, []
    for sample in ctx.samples():
        name = sample['dataset']
        path = ctx.out / 'fresh_evidence' / f'{name}.npz'
        if not path.with_suffix('.json').exists():
            continue
        fresh = load_graph(path)
        old = load_graph(ctx.v1 / 'baseline/public' / f'{name}.npz')
        votes = load_graph(ctx.v2 / 'predictions' / f'{name}.npz')
        native = load_graph(ctx.out / 'features' / f'{name}.npz')
        a, b = old['nodes'], fresh['old_nodes']
        identity = a.shape == b.shape and np.array_equal(a[:, :2], b[:, :2])
        row = dict(dataset=name, old_node_identity_exact=identity,
            old_nodes_exact=np.array_equal(a, b), old_edges_exact=np.array_equal(old['edges'], fresh['old_edges']),
            e_native_exact=np.array_equal(votes['E_native_m1.5__edges'], fresh['e_native']),
            e_hgb_exact=np.array_equal(votes['E_hgb_m1.5__edges'], fresh['e_hgb']),
            native_fields_exact={key: np.array_equal(value, fresh[key], equal_nan=True) for key, value in native.items()},
            native_fields_finite={key:bool(np.isfinite(fresh[key]).all()) for key in native},
            coordinate_changes=[])
        if identity and not row['old_nodes_exact']:
            compatibility_path = ctx.v2 / 'replay/identity' / name / 'complete.json'
            compatibility = read_json(compatibility_path).get('numerical_export_compatibility', [])
            tie = {(r['node_id'], r['axis']): r for r in compatibility}
            row['sealed_serializer_receipt_sha256'] = sha(compatibility_path)
            for i in np.flatnonzero(np.any(a[:, 2:] != b[:, 2:], axis=1)):
                causes = []
                for j in np.flatnonzero(a[i] != b[i]):
                    axis = 'id t z y x'.split()[j]
                    limit = sample['image_shape'][j-1]-1
                    key = (int(a[i, 0]), axis)
                    if b[i, j] == np.clip(a[i, j], 0, limit) and not 0 <= a[i, j] <= limit:
                        causes.append('upper_or_lower_bound')
                    elif key in tie and a[i, j] == tie[key]['sealed_integer'] and b[i, j] == tie[key]['native_integer']:
                        assert abs((tie[key]['unrounded'] % 1)-.5) <= 1e-10
                        causes.append('documented_half_integer_serialization')
                    else:
                        causes.append('unexplained')
                distance = float(np.linalg.norm((a[i, 2:]-b[i, 2:]) * sample['physical_scale']))
                shifted.append(distance)
                bounds_nodes += 'upper_or_lower_bound' in causes
                tie_nodes += 'documented_half_integer_serialization' in causes
                unexplained += 'unexplained' in causes
                row['coordinate_changes'].append(dict(node_id=int(a[i, 0]), causes=causes, physical_shift_um=distance))
        rows.append(row)
    if require_complete:
        assert len(rows) == len(ctx.samples()) == 199
    detailed = ctx.out / 'fresh_teacher_native_full_parity_audit.json'
    write_json(detailed, dict(comparison_only=True, samples=len(rows), rows=rows))
    summary = dict(samples=len(rows), expected_samples=len(ctx.samples()), comparison_only=True,
        used_for_prediction=False, old_teacher_node_identity_exact=all(r['old_node_identity_exact'] for r in rows),
        old_teacher_node_arrays_exact_clips=sum(r['old_nodes_exact'] for r in rows),
        old_teacher_coordinate_difference_clips=sum(not r['old_nodes_exact'] for r in rows),
        changed_old_teacher_nodes=len(shifted), bounded_nodes=bounds_nodes,
        documented_half_integer_serialization_nodes=tie_nodes, unexplained_coordinate_changes=unexplained,
        max_old_teacher_physical_shift_um=max(shifted, default=0.),
        all_old_teacher_edges_exact=all(r['old_edges_exact'] for r in rows),
        all_E_native_edges_exact=all(r['e_native_exact'] for r in rows),
        all_E_hgb_edges_exact=all(r['e_hgb_exact'] for r in rows),
        all_current_native_feature_fields_exact=all(all(r['native_fields_exact'].values()) for r in rows),
        all_current_native_numeric_arrays_finite=all(all(r['native_fields_finite'].values()) for r in rows),
        cause='Fresh canonical teacher enforces image bounds and uses native rounding. Original V1 retained six pre-existing out-of-bounds points and two documented ULP half-integer serializer values.',
        detailed_artifact=str(detailed), detailed_sha256=sha(detailed),
        original_report_sha256=sha(ctx.repo / 'results/strong-tracker-v2/v2_report.md'))
